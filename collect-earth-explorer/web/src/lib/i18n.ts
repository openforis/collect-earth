/** The twelve month names (January first) in the page's language. */
export const monthNames = (month: "long" | "short", in_: Lang = lang) =>
  Array.from({ length: 12 }, (_, m) => new Intl.DateTimeFormat(in_, { month, timeZone: "UTC" }).format(Date.UTC(2000, m, 1)));

/** The seven day names (Sunday first, as Plotly wants them) in the page's language. */
export const dayNames = (weekday: "long" | "short", in_: Lang = lang) =>
  // 2 January 2000 was a Sunday.
  Array.from({ length: 7 }, (_, d) => new Intl.DateTimeFormat(in_, { weekday, timeZone: "UTC" }).format(Date.UTC(2000, 0, 2 + d)));
