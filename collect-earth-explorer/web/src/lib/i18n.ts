// The interface texts in the five languages Collect Earth maintains, and the browser language that picks one.
// Every user-visible text needs a key here in all five; i18n.test.ts enforces that the dictionaries match.

export const LANGS = ["en", "es", "fr", "pt", "tr"] as const;
export type Lang = (typeof LANGS)[number];

/** The first of the browser's languages whose primary subtag is one of LANGS; English otherwise. */
export function pickLang(languages: readonly (string | undefined)[] | undefined): Lang {
  for (const l of languages ?? []) {
    const primary = l?.split(/[-_]/)[0].toLowerCase();
    if ((LANGS as readonly string[]).includes(primary ?? "")) return primary as Lang;
  }
  return "en";
}

