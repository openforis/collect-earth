export const CATALOGUES = { en, es, fr, pt } satisfies Record<string, Catalogue>;
export type Language = keyof typeof CATALOGUES;
export const LANGUAGES: Language[] = ["en", "es", "fr", "pt"];
export const LANGUAGE_NAMES: Record<Language, string> = { en: "English", es: "Español", fr: "Français", pt: "Português" };

export function isLanguage(value: string | null | undefined): value is Language {
  return typeof value === "string" && (LANGUAGES as string[]).includes(value);
}

/** The language to start in: the one chosen before, else the browser's first supported one, else English. */
export function pickLanguage(stored: string | null, browserLanguages: readonly string[]): Language {
  if (isLanguage(stored)) return stored;
  for (const tag of browserLanguages) {
    const base = tag.toLowerCase().split("-")[0];
    if (isLanguage(base)) return base;
  }
  return "en";
}

export function initialLanguage(): Language {
  const browser = typeof navigator === "undefined" ? [] : navigator.languages?.length ? navigator.languages : [navigator.language ?? ""];
  return pickLanguage(getStoredLanguage(), browser);
}

export type Translate = (key: MessageKey, params?: Record<string, string | number>) => string;

export function translator(language: string): Translate {
  const catalogue: Catalogue = isLanguage(language) ? CATALOGUES[language] : en;
  return (key, params) => {
    const text = catalogue[key] ?? en[key] ?? key;
    return params ? text.replace(/\{(\w+)\}/g, (m, name: string) => (name in params ? String(params[name]) : m)) : text;
  };
}

export const I18nContext = createContext<Translate>(translator("en"));

export function useT(): Translate {
  return useContext(I18nContext);
}
